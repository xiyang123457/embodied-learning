"""坐标变换小库：所有变换一律按 T_target_source 命名。

命名约定（本库唯一的规则）
    T_target_source 表示「把 source 系里的点，变到 target 系」：
        p_target = T_target_source @ p_source
    复合时下标相邻消去，与单位换算完全一致：
        T_base_obj = T_base_cam @ T_cam_obj
    写成 T_cam_base @ T_cam_obj 时下标对不上，乘积没有几何意义，
    但 numpy 不会报错，它会返回一个看着合法的数字（见 test_transforms 第 5 条，
    错写法给出 (0,0,0)，正确写法给出 (1,1,0)）。

用途
    给 W4 的雅可比有限差分、W5 的轨迹批量变换、W6 的 BC 输入预处理提供
    共用的旋转与齐次变换原语。只做到 4x4 齐次变换，不实现四元数、欧拉角、逆解。

输入输出
    全部函数接受 ndarray 或可转成 ndarray 的序列，返回 ndarray（dtype=float64）。
    apply 是批量的：输入 (3,) 或 (N,3)，一律返回 (N,3)。

跑完应看到的自检数字
    rot_y(pi/2) @ [0,0,1]                  -> [1, 0, 0]      （z 轴转到 x 轴）
    apply(compose(T_base_cam, T_cam_obj), [0,0,0]) -> [[1. 1. 0.]]
    apply(inverse(T), apply(T, [0,0,0]))   -> [[6.1e-17, 0, 0]]（浮点往返，不是精确 0）
    np.abs(inverse(T) @ T - np.eye(4)).max() -> 0.0
    apply(T, [[0,0,0],[1,0,0],[0,1,0]]).shape -> (3, 3)

怎么验证跑对了
    在仓库根目录跑 `python -m pytest tests/ -q`，6 条全绿；
    或单跑 `python -c "from src.transforms import *; import numpy as np;
    print(np.round(rot_y(np.pi/2) @ [0,0,1], 12))"`，应打印 [1. 0. 0.]
"""

# numpy：唯一依赖。
#   作用：三角函数、矩阵乘法、批量点变换。矩阵乘法走 BLAS，几百个点一次乘完，
#         比 for 循环快一个数量级，所以 apply 从一开始就写成批量。
#   为什么不用 scipy.spatial.transform.Rotation：它内部也返回 4x4 齐次矩阵，
#         但四元数分量顺序、欧拉角约定这些细节会把「方向」这件事藏起来，
#         本周的目标是让方向显式可见，所以自己写几十行。
import numpy as np


# ==== 1. 三个基本旋转 ====
# 三个矩阵都是二维 [[c,-s],[s,c]] 往对应轴上的推广。区别只在「哪个分量不动」：
#   绕 x 转，x 那一行和那一列固定为 (1,0,0)；绕 y、绕 z 同理。
# R_y 是唯一一个 sin 符号反着放的，因为绕 y 轴的循环方向是 z→x→z，与另两轴相反。

def rot_x(theta):
    """绕 x 轴转 theta 弧度，返回 (3,3)。"""
    c, s = np.cos(theta), np.sin(theta)
    # c：float，cos(theta)。theta=pi/2 时是 6.123e-17，不是 0
    #   why：直接调用 numpy 的浮点实现，不做 round。抹掉尾数会把误差藏起来，
    #        后面 allclose 反而判不准；真实浮点留着，由调用方用容差处理
    # s：float，sin(theta)。theta=pi/2 时是 1.0
    #   why：和 c 同一次调用取出来，避免重复算两次三角函数（小优化，主要为了对称好看）
    return np.array([[1.0, 0.0, 0.0],
                     [0.0, c, -s],
                     [0.0, s, c]])


def rot_y(theta):
    """绕 y 轴转 theta 弧度，返回 (3,3)。

    自检：rot_y(pi/2) @ [0,0,1] 应等于 [1,0,0]。
    把 -s 挪到右上角（写成 [[c,0,-s],[0,1,0],[s,0,c]]）会得到 [-1,0,0]，
    方向差 180 度。注意这个错版依然是正交阵、det 依然是 +1，所以
    「正交性」和「det=+1」两条单测都抓不到它，只有已知算例能抓。
    """
    c, s = np.cos(theta), np.sin(theta)
    # c / s：float，(6.123e-17, 1.0) 在 theta=pi/2 处
    #   why：R_y 的 sin 项分别落在 [0][2] 和 [2][0]，与 R_x/R_z 的 [0][1]/[1][0] 不同，
    #        这是唯一需要死记的一处符号，其余都是同一套规律
    return np.array([[c, 0.0, s],
                     [0.0, 1.0, 0.0],
                     [-s, 0.0, c]])


def rot_z(theta):
    """绕 z 轴转 theta 弧度，返回 (3,3)。"""
    c, s = np.cos(theta), np.sin(theta)
    # c / s：float，与上面同义
    #   why：二维那个 [[c,-s],[s,c]] 原封不动放进左上角，第三维补 1，
    #        因为绕 z 轴转时 z 分量不变
    return np.array([[c, -s, 0.0],
                     [s, c, 0.0],
                     [0.0, 0.0, 1.0]])


# ==== 2. 拼齐次矩阵 ====
# 第 4 维存在的唯一目的：把 p' = R p + t 这种「乘法加加法」压成纯乘法 p' = T p。
# 只有变成纯乘法，复合变换才能写成连乘，第二节那条「下标相邻消去」才成立。
# 代价是多存一行一列，且点必须先升到 (N,4)。这是本周最划算的一笔交易。

def make_T(R, t):
    """由 (3,3) 旋转和 (3,) 或 (3,1) 平移拼出 (4,4) 齐次矩阵。"""
    R = np.asarray(R, dtype=float)
    # np.asarray(x, dtype=float) -> ndarray
    #   作用：把 list / tuple / 已是 ndarray 的输入统一成 float64 数组
    #   关键参数：dtype=float 必须显式写。不写时整数列表会被保留成 int64，
    #             后续赋值给 np.eye(4) 的 float 槽位虽然能广播，但除法会截断
    #   坑：asarray 不复制已有 float64 数组，改返回值会改到调用方的变量；
    #       本函数只读不写，所以用 asarray 而不是 array，省一次内存拷贝
    t = np.asarray(t, dtype=float).reshape(-1)
    # reshape(-1) -> 一维，长度由元素总数决定
    #   作用：把列向量 (3,1) 和行向量 (3,) 抹平成同一种形状 (3,)
    #   关键参数：-1 表示"这一维自动算"，这里等价于 reshape(3)
    #   坑：不做这一步而直接 T[:3,3] = t 时，(3,1) 会触发 broadcast 报错，
    #       报错信息是 "could not broadcast input array from shape (3,1) into shape (3,)"，
    #       读起来完全不像形状问题。reshape 提前一步把错误消掉
    if R.shape != (3, 3) or t.size != 3:
        raise ValueError(f"R 需要 (3,3)，t 需要 3 个分量，收到 {R.shape} 和 {t.shape}")
        # why 显式抛错而不靠 broadcast 兜底：错形状有时能广播成功，
        #   结果是错的矩阵却在后面几十步才暴露。在这里拦住，错误位置就是出错位置

    T = np.eye(4)
    # np.eye(4) -> (4,4) 单位阵，对角为 1
    #   作用：一次拿到「旋转=单位、平移=0」的合法初值，顺带把最后一行 [0,0,0,1] 填好
    #   关键参数：4 是方阵边长，对应齐次坐标的 3 维位置加 1 维缩放
    #   坑：用 np.zeros 建再填时，最后一行会全 0，矩阵不可逆，apply 出来的第 4 分量是 0
    T[:3, :3] = R
    T[:3, 3] = t
    # 逗号索引 T[:3, :3] 是二维切片：前 3 行、前 3 列，即旋转块；T[:3, 3] 是最后一列的前 3 行，即平移
    return T


# ==== 3. 求逆 ====
# 用 [[Rᵀ, -Rᵀt], [0,1]] 而不是 np.linalg.inv。
# 理由有两条：旋转是正交阵，转置是精确且零开销的操作；通用求逆要做 LU 分解，
# 慢，而且会引入 1e-16 量级的误差，单测里「往返误差 < 1e-12」就过不了。
# 注意 T.T 不是逆。只有平移恰好为 0 时两者才碰巧相等。

def inverse(T):
    """返回 (4,4) 逆矩阵。T 必须是齐次变换矩阵。"""
    T = np.asarray(T, dtype=float)
    # 见 make_T 里同名调用，作用与坑完全一致
    R, t = T[:3, :3], T[:3, 3]
    # R：ndarray (3,3)，旋转块
    #   why：逆的旋转部分是 Rᵀ，先把 R 单独取出来，避免后面写 T[:3,:3].T 三次
    # t：ndarray (3,)，平移块
    #   why：逆的平移部分是 -Rᵀt，不是 -t。这个区别是本函数全部的意义所在

    Ti = np.eye(4)
    Ti[:3, :3] = R.T
    # R.T -> (3,3) 转置
    #   作用：正交阵的逆就是转置，这是便宜求逆的第一个前提
    #   关键参数：无，只对旋转块取转置，不能对整个 4x4 取转置
    #   坑：写成 T.T 会把平移塞进最后一行，得到的是"把点变到对偶空间"，
    #       数值上不为 0 但几何上毫无意义。算例里这个差是 1.0 米
    Ti[:3, 3] = -R.T @ t
    # R.T @ t -> (3,) 向量
    #   作用：先把平移量旋转到「目标系」的坐标轴下，再取负
    #   关键参数：矩阵在左、向量在右。写成 t @ R.T 得到的是 (3,)，但分量顺序是
    #             行向量约定，等价于先转后乘，结果不相等，也不报错
    #   坑：最常见的错是直接写 -t。以 rot_z(90°) + 平移 (1,0,0) 为例，
    #       -Rᵀt 得到 (0,1,0)，-t 得到 (-1,0,0)，差 √2 ≈ 1.41 米。
    #       而 R 为单位阵时两者碰巧相等，于是这个错最容易在手算时伪装成正确
    return Ti


# ==== 4. 批量变换点 ====
# 一开始就写成批量的。W5 要一次变几百个轨迹点，W4 的有限差分也要批量算，
# 那时再改签名会牵动所有调用方。现在多写三行，后面省一次重构。

def apply(T, points):
    """把点从 source 系变到 target 系。points 为 (3,) 或 (N,3)，返回 (N,3)。"""
    T = np.asarray(T, dtype=float)
    # 见 make_T 里同名调用
    P = np.atleast_2d(np.asarray(points, dtype=float))
    # np.atleast_2d(x) -> 至少二维的 ndarray
    #   作用：把单点 (3,) 补成 (1,3)，已经二维的原样返回
    #   关键参数：只补维度，不改数值
    #   坑：不补的话下面 P.shape[1] 会抛 IndexError，
    #       而写 if P.ndim == 1 分支会让后面出现两条乘法路径，容易只改对一条
    # P：(N,3) float64，N 是点的个数，单点输入时 N=1
    #   why 统一成二维：返回值形状只有一种，调用方不用判断"这次是不是单点"
    if P.shape[1] != 3:
        raise ValueError(f"points 需要 (N,3)，收到 {P.shape}")

    ones = np.ones((P.shape[0], 1))
    # ones：(N,1) float64，全 1
    #   why：齐次坐标的第 4 分量。它的作用是让 T 的平移列被原样加进结果，
    #        等价于 p' = R p + t。若第 4 分量是 0，点会被当作方向向量，平移不生效
    Ph = np.hstack([P, ones])
    # np.hstack([P, ones]) -> (N,4)
    #   作用：横向拼接，把 (N,3) 和 (N,1) 接成 (N,4)
    #   关键参数：两个数组行数必须相同，这里都是 N
    #   坑：用 np.concatenate 时必须写 axis=1，默认 axis=0 会接成 (N+1,3)，形状对不上后面的乘法
    # Ph：(N,4) float64，齐次坐标

    out = (T @ Ph.T).T
    # T @ Ph.T -> (4, N)
    #   作用：一次乘完所有点。矩阵乘法走 BLAS，N=500 时比 for 循环快约一个数量级
    #   关键参数：左侧 (4,4)，右侧 (4,N)，内维必须都是 4
    #   坑一：写成 Ph @ T 时维度也能对上（(N,4) @ (4,4)），但那是行向量约定。
    #         结果是 Rᵀp 而不是 Rp，旋转方向反了，而且平移整列被乘进第 4 个分量，
    #         位置上完全看不到平移量。这是本函数唯一会静默出错的地方
    #   坑二：忘了外层 .T 会得到 (4,N)，返回后形状检查能抓住，但错误信息指向返回行，
    #         看起来像 apply 的锅，其实是转置落错了位置
    # out：(N,4) float64，齐次结果，第 4 列全是 1
    return out[:, :3]
    # [:, :3] -> (N,3)
    #   作用：丢掉第 4 个分量，回到欧氏坐标
    #   关键参数：切片而不是除法。严格做法是除以第 4 分量做透视除法，
    #             但本库只处理刚体变换，第 4 分量恒为 1，除法是空操作
    #   坑：如果 T 不是刚体变换（比如含缩放），这里直接切会给出错误结果


# ==== 5. 连乘 ====
# compose 的返回也遵循 T_target_source：compose(A, B) = A @ B，
# 按传入顺序从左到右，与数学书写顺序一致。这一点必须和 apply 的"左乘"对上，
# 否则会出现"矩阵拼对了但点变反了"的错位。

def compose(*Ts):
    """按传入顺序左乘，返回 (4,4)。compose(A, B) 等于 A @ B，无参数时返回单位阵。"""
    if not Ts:
        return np.eye(4)
        # why 支持零参数：让"求一堆变换的乘积"能写成 for 循环的初值，
        #     不必先判断列表是否为空。空乘积在数学上定义为单位元
    out = np.asarray(Ts[0], dtype=float)
    # out：(4,4) float64，累乘器
    #   why 从第一个开始而不是从单位阵开始：少一次 4x4 乘法，
    #       更重要的是保留"第一个变换原样返回"的语义，方便调试

    for T in Ts[1:]:
        T = np.asarray(T, dtype=float)
        if out.shape != (4, 4) or T.shape != (4, 4):
            raise ValueError(f"compose 只接 (4,4)，收到 {out.shape} 和 {T.shape}")
            # why 在循环内检查：把 3x3 旋转误传进来的情况很常见，
            #     提前报错比让它乘出 (4,4) 以外的东西再去 apply 里报错要清楚
        out = out @ T
        # out @ T -> (4,4)
        #   作用：累积乘积。顺序固定为「已有的在左，新的在右」
        #   关键参数：两者都必须是 (4,4)
        #   坑：写成 T @ out 会得到反序复合，数值上是另一个变换，
        #       而且形状完全合法。这就是下标消去规则要防的那类错误
    return out
